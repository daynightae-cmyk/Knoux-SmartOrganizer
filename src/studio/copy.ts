export function describeError(error: unknown, locale: Locale): { code: string; message: string } {
  const raw = String((error as Error)?.message || error || '');
  const match = raw.match(/\b([A-Z][A-Z0-9_]{2,}):\s*(.*)$/);
  const code = match ? match[1] : '';
  const known = code ? ERROR_TEXT[code] : undefined;
  const message = known ? known[locale] : (match?.[2] || raw || studioCopy[locale].genericError);
  return { code, message };
}

